#!/usr/bin/env node
// Builds the security inventory (Phase 13 / #security's app table) by
// cross-referencing catalog.json's app list against each app's own
// security.json — never by adding security fields to catalog.json itself,
// which stays scoped to nav/catalog display (see security/README.md,
// "Catalog"). No dependencies: uses Node's built-in fetch (Node 18+) to read
// each other repo's security.json from raw.githubusercontent.com, since
// these are separate repos, not a local monorepo layout every environment
// running this script can assume.
//
// Usage: node scripts/generate-security-inventory.js
// Writes: security/inventory.json

const fs = require("fs");
const path = require("path");

const repoRoot = path.join(__dirname, "..");
const OWNER = "marincountygov";

async function fetchAppSecurityJson(repoId) {
  const url = `https://raw.githubusercontent.com/${OWNER}/${repoId}/main/security.json`;
  const response = await fetch(url);
  if (response.status === 404) return null;
  if (!response.ok) throw new Error(`Unexpected ${response.status} fetching ${url}`);
  return response.json();
}

async function main() {
  const catalog = JSON.parse(fs.readFileSync(path.join(repoRoot, "catalog.json"), "utf8"));
  const marinOsSecurity = JSON.parse(fs.readFileSync(path.join(repoRoot, "security.json"), "utf8"));

  // marin-os is in scope (security/README.md, "Scope") but doesn't list
  // itself in its own catalog.json, so it's added here explicitly rather
  // than expected to come from the fetch loop below.
  const entries = [
    {
      id: "marin-os",
      name: "MarinOS",
      url: "https://marincountygov.github.io/marin-os/",
      profile: marinOsSecurity.profile,
      lastReviewed: marinOsSecurity.review && marinOsSecurity.review.lastReviewed,
      status: "configured",
    },
  ];

  for (const app of catalog) {
    const security = await fetchAppSecurityJson(app.id);
    entries.push({
      id: app.id,
      name: app.name,
      url: app.url,
      profile: security ? security.profile : null,
      lastReviewed: security && security.review ? security.review.lastReviewed : null,
      status: security ? "configured" : "missing",
    });
  }

  const inventory = {
    $comment: "Generated by scripts/generate-security-inventory.js — do not edit directly.",
    generatedAt: new Date().toISOString(),
    apps: entries,
  };

  const outPath = path.join(repoRoot, "security", "inventory.json");
  fs.writeFileSync(outPath, JSON.stringify(inventory, null, 2) + "\n");
  console.log(`Wrote ${outPath}`);

  const missing = entries.filter((e) => e.status === "missing");
  if (missing.length) {
    console.log(`${missing.length} app(s) have no security.json yet: ${missing.map((e) => e.id).join(", ")}`);
  }
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
